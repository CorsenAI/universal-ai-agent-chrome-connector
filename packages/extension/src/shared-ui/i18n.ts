const language = (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage?.()) || 'en'
const table: Record<Key, string> = language.toLowerCase().startsWith('fr') ? fr : en

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
}
